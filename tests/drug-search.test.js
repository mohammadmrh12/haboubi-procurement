const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const root = require('node:path').join(__dirname, '..');
const app = fs.readFileSync(root + '/app.js', 'utf8');
const start = app.indexOf('function latinPhoneticKey(value)');
const end = app.indexOf('function editDistance(a,b)', start);
assert.ok(start >= 0 && end > start, 'drug search functions should exist');
const searchFunctions = app.slice(start, end);
const helpers = `
function clean(value){return value==null?'':String(value).replace(/\\s+/g,' ').trim()}
function norm(value){return clean(value).toLowerCase().normalize('NFKD').replace(/[\\u0300-\\u036f]/g,'').replace(/[أإآٱ]/g,'ا').replace(/ى/g,'ي').replace(/ک/g,'ك').replace(/ی/g,'ي').replace(/[ًٌٍَُِّْـ]/g,'').replace(/[^\\p{L}\\p{N}]+/gu,' ').trim()}
function editDistance(a,b){if(Math.abs(a.length-b.length)>3)return 99;let p=Array.from({length:b.length+1},(_,i)=>i);for(let i=1;i<=a.length;i++){let c=[i];for(let j=1;j<=b.length;j++)c[j]=Math.min(c[j-1]+1,p[j]+1,p[j-1]+(a[i-1]===b[j-1]?0:1));p=c}return p[b.length]}
`;
const context = { window: {}, Map, Math, Array, String };
vm.createContext(context);
vm.runInContext(fs.readFileSync(root + '/drug-aliases.js', 'utf8'), context);
vm.runInContext(helpers + searchFunctions + `this.score=(item,q)=>scoreItem(item,q); this.phonetic=latinPhoneticKey; this.norm=norm;`, context);
const rankStart = app.indexOf('  // Collapse exact duplicates by national code + full specification.');
const rankEnd = app.indexOf('  if (!hits.length)', rankStart);
assert.ok(rankStart >= 0 && rankEnd > rankStart, 'search result ranking block should exist');
const rankingCode = app.slice(rankStart, rankEnd).replace(/^  /gm, '');
const reviewStart = app.indexOf('// Review metadata is derived at runtime');
const reviewEnd = app.indexOf('function search() {', reviewStart);
const reviewHelpers = app.slice(reviewStart, reviewEnd);
const rankContext = { state: {items:[]}, query:'', translatedTerms:[], scoreItem:context.score, norm: value => String(value??'').toLowerCase().replace(/[^a-z0-9\u0600-\u06ff]+/g,' ').trim(), Number, Math, Array };
vm.createContext(rankContext);
vm.runInContext(reviewHelpers + `this.rank=(items,query)=>{state.items=items;const translatedTerms=[];${rankingCode};return hits}`, rankContext);
const capecitabine = { name: 'Capecitabine 500mg tablet', code: '15-AB0-099' };
assert.ok(context.score(capecitabine, 'xeloda') >= 1100, 'Xeloda should return capecitabine first');
assert.ok(context.score(capecitabine, 'زيلودا') >= 1100, 'Arabic spelling of Xeloda should return capecitabine');
assert.equal(context.phonetic('Xeloda'), context.phonetic('زيلودا'), 'Arabic and English brand transliterations should normalize together');
assert.ok(context.score({name:'Ceftriaxone 1g Injection'}, 'Ceftrixone') > 0, 'single-character misspellings should return close drug matches');
assert.ok(context.score({name:'Sterile Surgical Gloves'}, 'sterlie gloves') > 0, 'adjacent transposed letters and multi-token searches should match');
assert.ok(context.score({name:'Gauze Roll Sterile'}, 'gauz rol sterlie') > 0, 'multi-word typos should match by token rather than comparing the full phrase');
assert.equal(context.norm('كفوف ی'), context.norm('كفوف ي'), 'Arabic and Persian-style ya variants should normalize consistently');
assert.ok(context.score({ name: 'Paracetamol 500mg Tablet' }, 'acetaminophen') >= 1100, 'generic synonyms should cross-match');
assert.ok(context.score({ name: 'Medical Rubber Gloves examinaton Large (Pack x100)' }, 'كفوف فحص') >= 1100, 'Iraqi Arabic supply synonym should map to a medical glove catalogue item');
assert.ok(context.score({ name: 'glucose strips for glucometer' }, 'شرائط فحص السكر') >= 1100, 'laboratory/diagnostic supply synonyms should map to existing catalogue items');
assert.ok(context.score({ name: 'Furosemide 40mg Tablet' }, 'لازكس') >= 1100, 'Iraqi Ministry trade-name reference Lasix should map to the generic drug');
assert.ok(JSON.parse(fs.readFileSync(root + '/drug-aliases.json', 'utf8')).sourceUrls.some(url => url.includes('dta.gov.iq')), 'Iraqi Ministry source should be recorded in alias metadata');
const exactZero = {name:'Exact Material',code:'EX-1',annual:0};
const nearHigh = {name:'Exact Material alternative',code:'EX-2',annual:900};
const rankedExact = rankContext.rank([nearHigh, exactZero], 'Exact Material');
assert.equal(rankedExact[0].item.code, 'EX-1', 'exact name match with zero need must rank before approximate high-need match');
const nearLow = {name:'gauze roll small',code:'SUP-1',annual:10};
const nearHighNeed = {name:'gauze roll sterile',code:'SUP-2',annual:800};
const rankedApprox = rankContext.rank([nearLow, nearHighNeed], 'gauze rol');
assert.equal(rankedApprox[0].item.code, 'SUP-2', 'approximate matches should prioritize higher annual need');
const exactLow = {name:'Gauze Roll',code:'SUP-3',annual:0};
const exactHigh = {name:'Gauze Roll',code:'SUP-4',annual:700};
const rankedExactTies = rankContext.rank([exactLow, exactHigh], 'Gauze Roll');
assert.equal(rankedExactTies[0].item.code, 'SUP-4', 'among equally exact name matches, higher need may break the tie');
const aliases = JSON.parse(fs.readFileSync(root + '/drug-aliases.json', 'utf8')).aliases;
assert.ok(Object.keys(aliases).length >= 1000, 'researched brand crosswalk should contain broad brand coverage');
console.log(`PASS: brand/generic search, Arabic transliteration, synonyms, and ${Object.keys(aliases).length} trade-name aliases.`);
